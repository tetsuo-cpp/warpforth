# warpforthc --arch sm_70 output for a kernel with params A i64[4], B f64[4], N i64, X f64
# and shared S i64[8].
MIXED_PTX = """\
//
// Generated by LLVM NVPTX Back-End
//

.version 6.0
.target sm_70
.address_size 64

	// .globl	mixed
// __wg_mixed_0 has been demoted

.visible .entry mixed(
	.param .u64 .ptr .align 1 mixed_param_0,
	.param .u64 .ptr .align 1 mixed_param_1,
	.param .u64 mixed_param_2,
	.param .f64 mixed_param_3
)
{
	.reg .b32 	%r<3>;
	.reg .b64 	%rd<9>;
	// demoted variable
	.shared .align 8 .b8 __wg_mixed_0[64];
	ld.param.b64 	%rd1, [mixed_param_0];
	ld.param.b64 	%rd2, [mixed_param_1];
	mov.u32 	%r1, %tid.x;
	shl.b32 	%r2, %r1, 3;
	ld.param.b64 	%rd3, [mixed_param_2];
	cvt.u64.u32 	%rd4, %r2;
	ld.param.b64 	%rd5, [mixed_param_3];
	mov.b64 	%rd6, __wg_mixed_0;
	add.s64 	%rd7, %rd4, %rd6;
	st.shared.b64 	[%rd7], %rd3;
	bar.sync 	0;
	ld.shared.b64 	%rd8, [__wg_mixed_0];
	st.global.b64 	[%rd1], %rd8;
	st.global.b64 	[%rd2], %rd5;
	ret;

}
"""


class Conversation:
    """Drives serve() in a thread, one request and response at a time."""

    def __init__(self, driver: FakeDriver) -> None:
        self._requests: queue.Queue[str | None] = queue.Queue()
        self._responses: queue.Queue[dict] = queue.Queue()
        self._next_id = 0
        self.status: int | None = None
        self._thread = threading.Thread(target=self._serve, args=(driver,), daemon=True)
        self._thread.start()

    def _serve(self, driver: FakeDriver) -> None:
        self.status = serve(driver, iter(self._requests.get, None), self)

    def write(self, text: str) -> None:
        self._responses.put(json.loads(text))

    def flush(self) -> None:
        pass

    def send_line(self, line: str) -> dict:
        self._requests.put(line + "\n")
        return self._responses.get(timeout=5)

    def send(self, op: str, **fields: object) -> dict:
        self._next_id += 1
        response = self.send_line(json.dumps({"id": self._next_id, "op": op, **fields}))
        assert response["id"] == self._next_id
        return response

    def ok(self, op: str, **fields: object) -> dict:
        response = self.send(op, **fields)
        assert response["ok"], response
        return response["result"]

    def stopped(self) -> bool:
        self._thread.join(timeout=5)
        return not self._thread.is_alive()

    def finish(self) -> int | None:
        self._requests.put(None)
        self._thread.join(timeout=5)
        return self.status


def b64(data: bytes) -> str:
    return base64.b64encode(data).decode()


def test_parse_entries_reads_parameter_kinds_from_warpforthc_ptx() -> None:
    assert parse_entries(MIXED_PTX) == {"mixed": ["ptr", "ptr", "i64", "f64"]}


def test_parse_entries_handles_several_entries_and_empty_parameter_lists() -> None:
    ptx = (
        ".visible .entry first(\n\t.param .s64 first_param_0\n)\n{\n\tret;\n}\n"
        ".visible .entry second()\n{\n\tret;\n}\n"
    )
    assert parse_entries(ptx) == {"first": ["i64"], "second": []}


@pytest.mark.parametrize(
    "param",
    [".param .u32 k_param_0", ".param .align 8 .b8 k_param_0[16]", ".param .f32 k_param_0"],
)
def test_parse_entries_rejects_unsupported_parameters(param: str) -> None:
    with pytest.raises(ValueError, match="unsupported kernel parameter"):
        parse_entries(f".visible .entry k(\n\t{param}\n)\n{{\n}}\n")


def test_load_reports_kernels_and_their_parameter_kinds() -> None:
    chat = Conversation(FakeDriver())
    result = chat.ok("load", ptx=MIXED_PTX)
    assert result["kernels"] == {"mixed": ["ptr", "ptr", "i64", "f64"]}
    assert isinstance(result["module"], int)
    assert chat.finish() == 0


def test_partial_write_then_read_returns_the_whole_zeroed_buffer() -> None:
    chat = Conversation(FakeDriver())
    buffer = chat.ok("alloc", size=8)["buffer"]
    assert base64.b64decode(chat.ok("read", buffer=buffer)["data"]) == bytes(8)
    chat.ok("write", buffer=buffer, data=b64(b"\x01\x02\x03"))
    assert base64.b64decode(chat.ok("read", buffer=buffer)["data"]) == b"\x01\x02\x03" + bytes(5)
    assert chat.finish() == 0


def test_launch_packs_arguments_in_ptx_order() -> None:
    driver = FakeDriver()
    chat = Conversation(driver)
    module = chat.ok("load", ptx=MIXED_PTX)["module"]
    a = chat.ok("alloc", size=32)["buffer"]
    b = chat.ok("alloc", size=32)["buffer"]
    chat.ok(
        "launch",
        module=module,
        kernel="mixed",
        grid=[2, 1, 1],
        block=[64, 1, 1],
        args=[{"buffer": a}, {"buffer": b}, {"value": -7}, {"value": 2}],
    )
    pointer_a, pointer_b = driver.pointers
    assert len(driver.launches) == 1
    launch = driver.launches[0]
    assert (launch.kernel, launch.grid, launch.block) == ("mixed", (2, 1, 1), (64, 1, 1))
    assert launch.args == [
        (ctypes.c_uint64, pointer_a),
        (ctypes.c_uint64, pointer_b),
        (ctypes.c_int64, -7),
        (ctypes.c_double, 2.0),
    ]
    assert chat.finish() == 0


@pytest.mark.parametrize(
    "args",
    [
        [{"value": 1}, {"value": 2}, {"value": 3}],
        [{"buffer": 999}, {"buffer": 999}, {"value": 1}, {"value": 1.0}],
        ["not-a-buffer", "B", {"value": 1}, {"value": 1.0}],
        ["A", "B", {"value": 1.5}, {"value": 1.0}],
        ["A", "B", {"value": True}, {"value": 1.0}],
        ["A", "B", {"value": 2**63}, {"value": 1.0}],
        ["A", "B", {"value": 1}, {"value": "1.0"}],
        ["A", {"value": 0}, {"value": 1}, {"value": 1.0}],
    ],
    ids=[
        "wrong-count",
        "unknown-buffer",
        "ptr-as-string",
        "float-for-i64",
        "bool-for-i64",
        "i64-overflow",
        "string-for-f64",
        "value-for-ptr",
    ],
)
def test_bad_launch_arguments_are_rejected_without_launching(args: list[object]) -> None:
    driver = FakeDriver()
    chat = Conversation(driver)
    module = chat.ok("load", ptx=MIXED_PTX)["module"]
    buffers = {"A": chat.ok("alloc", size=32)["buffer"], "B": chat.ok("alloc", size=32)["buffer"]}
    resolved = [{"buffer": buffers[a]} if a in ("A", "B") else a for a in args]
    response = chat.send(
        "launch", module=module, kernel="mixed", grid=[1, 1, 1], block=[1, 1, 1], args=resolved
    )
    assert response["ok"] is False
    assert response["error"]["code"] == "BAD_REQUEST"
    assert response["fatal"] is False
    assert driver.launches == []
    chat.ok("read", buffer=buffers["A"])
    assert chat.finish() == 0


@pytest.mark.parametrize(
    ("line", "expected_id"),
    [
        ("{not json", None),
        ('{"op": "alloc", "size": 8}', None),
        ('{"id": 4, "op": "explode"}', 4),
        ('{"id": 5, "op": "read", "buffer": 12345}', 5),
        ('{"id": 6, "op": "alloc", "size": 0}', 6),
        ('{"id": 7, "op": "write", "buffer": 1, "data": "AAAAAAAAAAAA"}', 7),
        ('{"id": 8, "op": "launch", "module": 77, "kernel": "mixed"}', 8),
    ],
    ids=[
        "malformed-json",
        "missing-id",
        "unknown-op",
        "unknown-buffer",
        "zero-size",
        "write-past-end",
        "unknown-module",
    ],
)
def test_bad_requests_are_answered_and_the_worker_keeps_serving(
    line: str, expected_id: int | None
) -> None:
    chat = Conversation(FakeDriver())
    chat.ok("alloc", size=8)
    response = chat.send_line(line)
    assert response == {
        "id": expected_id,
        "ok": False,
        "error": {"code": "BAD_REQUEST", "message": response["error"]["message"]},
        "fatal": False,
    }
    chat.ok("alloc", size=8)
    assert chat.finish() == 0


def test_load_driver_error_is_not_fatal() -> None:
    chat = Conversation(FakeDriver(load_error="CUDA_ERROR_INVALID_PTX"))
    response = chat.send("load", ptx=MIXED_PTX)
    assert response["error"]["code"] == "CUDA_ERROR_INVALID_PTX"
    assert "parse error" in response["error"]["message"]
    assert response["fatal"] is False
    chat.ok("alloc", size=8)
    assert chat.finish() == 0


def test_launch_driver_error_is_fatal_and_stops_the_worker() -> None:
    chat = Conversation(FakeDriver(launch_error="CUDA_ERROR_ILLEGAL_ADDRESS"))
    module = chat.ok("load", ptx=MIXED_PTX)["module"]
    a = chat.ok("alloc", size=32)["buffer"]
    response = chat.send(
        "launch",
        module=module,
        kernel="mixed",
        grid=[1, 1, 1],
        block=[1, 1, 1],
        args=[{"buffer": a}, {"buffer": a}, {"value": 1}, {"value": 1.0}],
    )
    assert response["ok"] is False
    assert response["error"]["code"] == "CUDA_ERROR_ILLEGAL_ADDRESS"
    assert response["fatal"] is True
    assert chat.stopped()
    assert chat.status == 1


def fake_worker_argv(**driver_options: str) -> list[str]:
    code = (
        "import sys\n"
        f"sys.path.insert(0, {str(PROJECT_ROOT)!r})\n"
        "from gpu_test.fake_driver import FakeDriver\n"
        "from warpforth_gpu.worker import serve\n"
        f"sys.exit(serve(FakeDriver(**{driver_options!r}), sys.stdin, sys.stdout))\n"
    )
    return [sys.executable, "-u", "-c", code]


def test_client_round_trips_buffers_through_a_worker_process() -> None:
    with Device.spawn(fake_worker_argv()) as device:
        module = device.load(MIXED_PTX)
        assert module.kernel("mixed").kinds == ("ptr", "ptr", "i64", "f64")
        values = np.array([1.5, -2.25, 3.0], dtype=np.float64)
        buffer = device.upload(values)
        assert buffer.size == 24
        np.testing.assert_array_equal(buffer.read(np.float64), values)
        other = device.alloc(32)
        module.kernel("mixed").launch(args=[buffer, other, np.int64(3), 0.5])
        buffer.free()
        with pytest.raises(DeviceError) as excinfo:
            buffer.read(np.float64)
        assert excinfo.value.code == "BAD_REQUEST"
        assert not device.closed


def test_client_closes_after_a_fatal_launch_error() -> None:
    with Device.spawn(fake_worker_argv(launch_error="CUDA_ERROR_ILLEGAL_ADDRESS")) as device:
        kernel = device.load(MIXED_PTX).kernel("mixed")
        buffer = device.alloc(32)
        with pytest.raises(DeviceError) as excinfo:
            kernel.launch(args=[buffer, buffer, 1, 1.0])
        assert excinfo.value.code == "CUDA_ERROR_ILLEGAL_ADDRESS"
        assert device.closed
        with pytest.raises(DeviceError) as excinfo:
            device.alloc(8)
        assert excinfo.value.code == "CLOSED"


@pytest.mark.skipif(ctypes.util.find_library("cuda") is not None, reason="CUDA is installed")
def test_worker_without_cuda_exits_and_the_client_reports_its_stderr() -> None:
    with Device.spawn(worker_command(sys.executable)) as device:
        with pytest.raises(DeviceError) as excinfo:
            device.alloc(8)
        assert excinfo.value.code == "WORKER_EXITED"
        assert "cannot initialize CUDA" in excinfo.value.message
        assert device.closed
